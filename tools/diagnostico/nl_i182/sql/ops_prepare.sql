SET @n = 'notalivre_migracao';
SET @t = 0;
SELECT 'P01 PREPARE SELECT GET_LOCK com parametros' AS op;
PREPARE s FROM 'SELECT GET_LOCK(?, ?) AS trava';
EXECUTE s USING @n, @t;
SELECT 'P02 PREPARE CREATE DATABASE' AS op;
PREPARE s FROM 'CREATE DATABASE notalivre_pp';
EXECUTE s;
SELECT 'P03 PREPARE CREATE TABLE' AS op;
PREPARE s FROM 'CREATE TABLE notalivre_pp.a (id INT NOT NULL PRIMARY KEY, w INT) ENGINE=InnoDB';
EXECUTE s;
SELECT 'P04 PREPARE ALTER TABLE' AS op;
PREPARE s FROM 'ALTER TABLE notalivre_pp.a ADD COLUMN z INT NULL';
EXECUTE s;
SELECT 'P05 PREPARE CREATE INDEX' AS op;
PREPARE s FROM 'CREATE INDEX ix ON notalivre_pp.a (w)';
EXECUTE s;
SELECT 'P06 PREPARE DROP INDEX' AS op;
PREPARE s FROM 'DROP INDEX ix ON notalivre_pp.a';
EXECUTE s;
SELECT 'P07 PREPARE CREATE TABLE LIKE' AS op;
PREPARE s FROM 'CREATE TABLE notalivre_pp.b LIKE notalivre_pp.a';
EXECUTE s;
SELECT 'P08 PREPARE INSERT SELECT' AS op;
PREPARE s FROM 'INSERT INTO notalivre_pp.b SELECT * FROM notalivre_pp.a';
EXECUTE s;
SELECT 'P09 PREPARE CREATE DATABASE 2' AS op;
PREPARE s FROM 'CREATE DATABASE notalivre_pq';
EXECUTE s;
SELECT 'P10 PREPARE RENAME TABLE entre bancos em lote' AS op;
PREPARE s FROM 'RENAME TABLE notalivre_pp.a TO notalivre_pq.a, notalivre_pp.b TO notalivre_pp.a';
EXECUTE s;
SELECT 'P11 PREPARE CREATE TEMPORARY TABLE' AS op;
PREPARE s FROM 'CREATE TEMPORARY TABLE tmp_p (x INT)';
EXECUTE s;
SELECT 'P12 PREPARE LOCK TABLES' AS op;
PREPARE s FROM 'LOCK TABLES notalivre_pp.a WRITE';
EXECUTE s;
UNLOCK TABLES;
SELECT 'P13 PREPARE DROP TABLE' AS op;
PREPARE s FROM 'DROP TABLE notalivre_pq.a';
EXECUTE s;
SELECT 'P14 PREPARE DROP DATABASE' AS op;
PREPARE s FROM 'DROP DATABASE notalivre_pq';
EXECUTE s;
SELECT 'P15 PREPARE DROP DATABASE 2' AS op;
PREPARE s FROM 'DROP DATABASE notalivre_pp';
EXECUTE s;
SELECT 'P16 PREPARE SELECT RELEASE_LOCK' AS op;
PREPARE s FROM 'SELECT RELEASE_LOCK(?) AS liberou';
EXECUTE s USING @n;
SELECT 'FIM' AS op;
